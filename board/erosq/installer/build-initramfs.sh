#!/usr/bin/env bash
# Build the installer's initramfs (a gzip'd cpio) from a finished Buildroot
# build of erosq_defconfig. Called by ci/installer.sh uimage.
#   build-initramfs.sh <work-dir> <buildroot-src> <buildroot-output> <u-boot-initial-env> <out.cpio.gz>
#
# What goes in:
#  - busybox, built here as a static binary (busybox's defconfig, Buildroot's
#    pinned tarball and patches). The firmware's busybox is cut down and has
#    no stat or timeout, which init needs; the installer proven on hardware
#    used a defconfig busybox too. One link per applet in initramfs.applets:
#    this busybox has no SH_STANDALONE, so an applet without its link is "not
#    found" and init cannot tell.
#  - mtd-utils, fw_printenv/fw_setenv and their libraries, from the target
#    (the busybox mtd applets fail on this kernel).
#  - init, install-lib.sh, and the U-Boot default environment the installer
#    seeds after it erases uboot-env (generated by ci/uboot.sh from the same
#    U-Boot it writes; a stored env replaces the built-in one wholesale).
# Env: CROSS (default the SDK's mipsel-linux-), BR2_DL_DIR, SOURCE_DATE_EPOCH, JOBS.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
EXT=$(cd "$HERE/../../.." && pwd)
fail() { echo "build-initramfs: FATAL: $*" >&2; exit 1; }
[ $# -eq 5 ] || fail "usage: $0 <work-dir> <buildroot-src> <buildroot-output> <u-boot-initial-env> <out.cpio.gz>"
W=$(mkdir -p "$1" && cd "$1" && pwd)
BR=$(cd "$2" && pwd) BO=$(cd "$3" && pwd) ENV=$4 OUT=$5
T=$BO/target
CROSS=${CROSS:-$EXT/sdk/bin/mipsel-linux-}
[ -x "${CROSS}gcc" ] || fail "no cross compiler ${CROSS}gcc"
[ -d "$T" ] || fail "$T: no Buildroot target directory"
[ -f "$ENV" ] || fail "$ENV: no such file"

# Public builds carry no SSH key, and nothing of a private build may end up
# in an installer that is published.
if [ -f "$BO/.config" ] && grep -q '^BR2_PACKAGE_EROSQ_BOARD_SEED_AUTHORIZED_KEYS="..*"' "$BO/.config"; then
	fail "$BO is a private build (BR2_PACKAGE_EROSQ_BOARD_SEED_AUTHORIZED_KEYS is set)"
fi

# The environment must be the A/B one, with the card fallback (the same
# gate as u-boot.bin's), and the kernel arguments the slots boot with.
"$EXT/ci/uboot-env-check.sh" "$ENV"
# fw_setenv -s applies the lines in order, so for a key listed twice the
# last line is what the chip gets (the file is sorted, and U-Boot's own empty
# `altbootcmd=` sorts before the board's). Each key the A/B boot reads must
# end up non-empty.
for k in bootcmd altbootcmd abselect boot_slot bootlimit baseargs; do
	v=$(grep "^$k=" "$ENV" | tail -n1) || true
	[ -n "${v#*=}" ] || fail "$ENV: $k ends up empty or missing"
done

# --- busybox ---------------------------------------------------------------
BBV=$(sed -n 's/^BUSYBOX_VERSION = //p' "$BR/package/busybox/busybox.mk" 2>/dev/null) || BBV=
[ -n "$BBV" ] || fail "no BUSYBOX_VERSION in $BR/package/busybox/busybox.mk"
TB=${BR2_DL_DIR:-$BR/dl}/busybox/busybox-$BBV.tar.bz2
[ -f "$TB" ] || { mkdir -p "${TB%/*}"; wget -q -O "$TB" "https://www.busybox.net/downloads/busybox-$BBV.tar.bz2"; }
SUM=$(awk -v f="busybox-$BBV.tar.bz2" '$1 == "sha256" && $3 == f {print $2}' "$BR/package/busybox/busybox.hash")
[ -n "$SUM" ] || fail "no sha256 for busybox-$BBV in busybox.hash"
echo "$SUM  $TB" | sha256sum -c --quiet - || fail "$TB: sha256 mismatch"
BB=$W/busybox-$BBV
rm -rf "$BB" && tar -xjf "$TB" -C "$W"
for p in "$BR"/package/busybox/*.patch; do
	[ -e "$p" ] || continue
	patch -s -d "$BB" -p1 < "$p" || fail "busybox patch ${p##*/} does not apply"
done
BBM=(make -C "$BB" ARCH=mips CROSS_COMPILE="$CROSS" KCONFIG_NOTIMESTAMP=1)
"${BBM[@]}" -s defconfig >/dev/null
sed -i 's/^# CONFIG_STATIC is not set$/CONFIG_STATIC=y/' "$BB/.config"
{ yes '' || true; } | "${BBM[@]}" -s oldconfig >/dev/null
grep -qx 'CONFIG_STATIC=y' "$BB/.config" || fail "busybox: CONFIG_STATIC did not stick"
"${BBM[@]}" -j"${JOBS:-$(nproc)}" busybox > "$W/busybox.log" 2>&1 || { tail -n 30 "$W/busybox.log"; fail "busybox build failed"; }
"${BBM[@]}" -s busybox.links >/dev/null
"${CROSS}readelf" -d "$BB/busybox" | grep -q NEEDED && fail "busybox is not static"

# --- the tree --------------------------------------------------------------
R=$W/root
rm -rf "$R" && mkdir -p "$R"/{bin,sbin,usr/bin,usr/sbin,lib,etc,dev,proc,sys,mnt,ubi,tmp}
install -m755 "$BB/busybox" "$R/bin/busybox"
"${CROSS}strip" "$R/bin/busybox"
while read -r a; do
	case "$a" in ''|'#'*) continue ;; esac
	grep -qE "/$a\$" "$BB/busybox.links" || fail "busybox has no '$a' applet (initramfs.applets)"
	ln -s busybox "$R/bin/$a"
done < "$HERE/initramfs.applets"

for b in nandwrite flash_erase ubiformat ubiattach ubidetach ubimkvol ubiupdatevol nanddump ubinfo; do
	[ -f "$T/usr/sbin/$b" ] || fail "$T/usr/sbin/$b missing (mtd-utils not in the build?)"
	install -m755 "$T/usr/sbin/$b" "$R/usr/sbin/$b"
done
install -m755 "$T/usr/bin/fw_printenv" "$R/usr/bin/fw_printenv"
ln -s fw_printenv "$R/usr/bin/fw_setenv"
install -m755 "$T/lib/libc.so" "$R/lib/libc.so"
ln -s libc.so "$R/lib/ld-musl-mipsel.so.1"
# every library an ELF here needs, dereferenced (a copied link would dangle)
for e in "$R"/usr/sbin/* "$R/usr/bin/fw_printenv"; do
	for l in $("${CROSS}readelf" -d "$e" | sed -n 's/.*(NEEDED).*\[\(.*\)\]/\1/p'); do
		[ -e "$R/lib/$l" ] && continue
		s=; for d in "$T/usr/lib" "$T/lib"; do [ -e "$d/$l" ] && { s=$d/$l; break; }; done
		[ -n "$s" ] || fail "${e##*/} needs $l, not in $T"
		cp -L "$s" "$R/lib/$l"
	done
done
install -m644 "$T/etc/fw_env.config" "$R/etc/fw_env.config"
install -m644 "$ENV" "$R/uboot-initial-env"
install -m755 "$HERE/install-lib.sh" "$R/install-lib.sh"
install -m755 "$HERE/init" "$R/init"

# Reproducible: fixed times, root-owned, sorted. INITRAMFS_SOURCE is linked
# into the kernel, so any jitter here changes the installer uImage.
find "$R" -exec touch -h -d "@${SOURCE_DATE_EPOCH:-0}" {} +
(cd "$R" && find . | LC_ALL=C sort | cpio -o -H newc -R 0:0 --reproducible --quiet | gzip -n -9) > "$OUT"
echo "initramfs: $(stat -c %s "$OUT") bytes, busybox $BBV ($(grep -c . "$BB/busybox.links") applets)"
